pub struct AdminUserConfig {
    pub email: String,
    pub password: String,
    pub name: String,
    pub role: String,
    pub is_developer: bool,
}

fn parse_admin_user(value: &str) -> Option<AdminUserConfig> {
    let parts: Vec<&str> = value.splitn(5, ',').map(|part| part.trim()).collect();
    if parts.len() < 5 || parts.iter().any(|part| part.is_empty()) {
        return None;
    }

    Some(AdminUserConfig {
        email: parts[0].to_string(),
        password: parts[1].to_string(),
        name: parts[2].to_string(),
        role: parts[3].to_string(),
        is_developer: parts[4].eq_ignore_ascii_case("true"),
    })
}

fn parse_dotenv_value(contents: &str, key: &str) -> Option<String> {
    contents.lines().find_map(|line| {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            return None;
        }

        let line = line.strip_prefix("export ").unwrap_or(line);
        let (candidate_key, value) = line.split_once('=')?;
        if candidate_key.trim() != key {
            return None;
        }

        let value = value.trim();
        Some(
            value
                .strip_prefix('"')
                .and_then(|value| value.strip_suffix('"'))
                .or_else(|| {
                    value
                        .strip_prefix('\'')
                        .and_then(|value| value.strip_suffix('\''))
                })
                .unwrap_or(value)
                .to_string(),
        )
    })
}

/// Resolve the configured admin user from:
/// 1. The `ADMIN_USER` environment variable (runtime),
/// 2. Values baked into the binary at build time (repository `.env`),
/// in that order.
pub fn configured_admin_user() -> Option<AdminUserConfig> {
    std::env::var("ADMIN_USER")
        .ok()
        .and_then(|value| parse_admin_user(&value))
        .or_else(|| {
            // Pairs are generated by build.rs from the repository `.env`.
            include!(concat!(env!("OUT_DIR"), "/build_env.rs"))
                .iter()
                .find(|(key, _)| *key == "ADMIN_USER")
                .map(|(_, value)| *value)
                .and_then(parse_admin_user)
        })
        .or_else(|| {
            // Also look for a `.env` next to the executable for packaged installs.
            if let Ok(exe_path) = std::env::current_exe() {
                if let Some(exe_dir) = exe_path.parent() {
                    if let Ok(contents) = std::fs::read_to_string(exe_dir.join(".env")) {
                        if let Some(value) = parse_dotenv_value(&contents, "ADMIN_USER") {
                            return parse_admin_user(&value);
                        }
                    }
                }
            }
            None
        })
}

/// Value source used by the build-time bake: mostly kept for documentation.
#[allow(dead_code)]
pub type BuildEnvPairs = (&'static str, &'static str);
